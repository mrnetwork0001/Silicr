//! Recipient guard: the sidecar's own check, independent of the TypeScript `toOrchardOnly`.
//! Only unified addresses with an Orchard receiver are accepted, and only that receiver is
//! ever paid. Transparent, TEX, Sapling and wrong-network addresses are refused.

use zcash_keys::address::{Address, UnifiedAddress};
use zcash_protocol::consensus::Network;

use crate::remote::chain_name;

/// Returns the Orchard-only UA encoding of `s` (the Orchard receiver re-encoded on its own)
/// and the Orchard receiver, or a human-readable reason for refusing it.
pub fn orchard_only(params: &Network, s: &str) -> Result<(String, orchard::Address), String> {
    let s = s.trim();
    let zaddr: zcash_address::ZcashAddress = s
        .parse()
        .map_err(|e| format!("not a Zcash address ({e})"))?;
    let addr = Address::try_from_zcash_address(params, zaddr)
        .map_err(|e| format!("not a {}net address this wallet can pay ({e})", chain_name(*params)))?;
    match addr {
        Address::Unified(ua) => {
            let o = *ua
                .orchard()
                .ok_or_else(|| "unified address has no Orchard receiver; refusing (Orchard receivers only)".to_string())?;
            Ok((encode_orchard(params, o), o))
        }
        Address::Sapling(_) => Err("Sapling address refused: Silicr pays Orchard receivers only".into()),
        Address::Transparent(_) => Err("transparent address refused: it would reveal the amount and recipient on-chain".into()),
        Address::Tex(_) => Err("TEX (transparent-source-only) address refused".into()),
    }
}

/// The Orchard-only unified address for an Orchard receiver. Deterministic, so the same
/// receiver always yields the same string (used to label received notes).
pub fn encode_orchard(params: &Network, o: orchard::Address) -> String {
    UnifiedAddress::from_receivers(Some(o), None, None)
        .expect("an Orchard receiver is a shielded receiver")
        .encode(params)
}

#[cfg(test)]
mod tests {
    use super::*;

    const NET: Network = Network::TestNetwork;

    #[test]
    fn refuses_non_orchard() {
        // Testnet transparent P2PKH.
        assert!(orchard_only(&NET, "tmWK81GXyxz8D259FJPkmfpdLXD32F741co").is_err());
        // Testnet Sapling.
        assert!(
            orchard_only(&NET, "ztestsapling1v6wh0dawepflf7yx5722fr77yatrl22hmg0ffd2tdxfl9rr356fper8gznajnl6ww3tuj67zv60").is_err()
        );
        assert!(orchard_only(&NET, "garbage").is_err());
    }

    #[test]
    fn strips_to_orchard_only() {
        // A testnet UA with Orchard + Sapling + P2PKH receivers (generated by zcash-devtool).
        let full = "utest1cc6xtxg57vq4ca6p8vej87zw03wph4jgg0z4z7ws620js6hgxx98xufcxkqeeeslysr8f9rzufqfnhtefjj93qa7pwnhfke9aqpxf95vsffm5jz0c0vvmejp6z5haegle7uxjtkhjfm69sttekp860q04xn8ugyeq5cyfz83g645ug9ys8xeu7cc7lf32lnxpwqve00vudshuumsnpn";
        let (only, _) = orchard_only(&NET, full).unwrap();
        assert_eq!(
            only,
            "utest1th74wdjrhclrr3klkgwzv63jhd224vvk0ta5h9urlwndm5pv2v29e2x8jgk5ekkk5e9w9me2k7yc7r8up8k2y866kwh03llcuctp0pdt"
        );
        // Idempotent.
        assert_eq!(orchard_only(&NET, &only).unwrap().0, only);
        // Mainnet encoding of anything is refused on a testnet wallet.
        assert!(orchard_only(&Network::MainNetwork, &only).is_err());
    }

    #[test]
    fn mainnet_addresses_are_u1_and_never_cross_networks() {
        let full = "utest1cc6xtxg57vq4ca6p8vej87zw03wph4jgg0z4z7ws620js6hgxx98xufcxkqeeeslysr8f9rzufqfnhtefjj93qa7pwnhfke9aqpxf95vsffm5jz0c0vvmejp6z5haegle7uxjtkhjfm69sttekp860q04xn8ugyeq5cyfz83g645ug9ys8xeu7cc7lf32lnxpwqve00vudshuumsnpn";
        let (_, receiver) = orchard_only(&NET, full).unwrap();
        // The same Orchard receiver encoded for mainnet is a `u1…` Orchard-only UA that round-trips there…
        let main = encode_orchard(&Network::MainNetwork, receiver);
        assert!(main.starts_with("u1"), "{main}");
        let (again, r2) = orchard_only(&Network::MainNetwork, &main).unwrap();
        assert_eq!(again, main);
        assert_eq!(r2, receiver);
        // …and is refused by a testnet wallet, with the network named in the reason.
        let err = orchard_only(&NET, &main).unwrap_err();
        assert!(err.contains("testnet address"), "{err}");
        assert!(orchard_only(&Network::MainNetwork, full).unwrap_err().contains("mainnet address"));
    }
}
